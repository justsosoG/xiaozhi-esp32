#ifndef ESP32_S3_DEVKITC1_2WD_CONFIG_H_
#define ESP32_S3_DEVKITC1_2WD_CONFIG_H_
#include <driver/gpio.h>
#include <esp_codec_dev_defaults.h>
#define AUDIO_INPUT_SAMPLE_RATE 24000
#define AUDIO_OUTPUT_SAMPLE_RATE 24000
// 本模块在板内把 ES8311 的一路输出回接到 ES7210 的第 3 通道（文档中的 "3P（AEC 回声）"），
// 因此第二通道可用作 AEC 参考输入，配合 CONFIG_USE_DEVICE_AEC 实现实时打断。
#define AUDIO_INPUT_REFERENCE true
#define AUDIO_I2S_GPIO_MCLK GPIO_NUM_15
#define AUDIO_I2S_GPIO_BCLK GPIO_NUM_5
#define AUDIO_I2S_GPIO_WS GPIO_NUM_4
#define AUDIO_I2S_GPIO_DOUT GPIO_NUM_7
#define AUDIO_I2S_GPIO_DIN GPIO_NUM_6
// LCD 已占用 GPIO41/42，因此 Codec 的 I2C 改用空闲的 GPIO1/2。
#define AUDIO_CODEC_I2C_SDA_PIN GPIO_NUM_1
#define AUDIO_CODEC_I2C_SCL_PIN GPIO_NUM_2
#define AUDIO_CODEC_PA_PIN GPIO_NUM_38
#define AUDIO_CODEC_ES8311_ADDR ES8311_CODEC_DEFAULT_ADDR
// 本板 ES7210 的 ADDR 引脚接高，7 位地址为 0x41（默认 0x40 会无应答）。
#define AUDIO_CODEC_ES7210_ADDR 0x82
#define MOTOR_AIN1_GPIO GPIO_NUM_8
#define MOTOR_AIN2_GPIO GPIO_NUM_9
#define MOTOR_PWMA_GPIO GPIO_NUM_10
#define MOTOR_BIN1_GPIO GPIO_NUM_11
#define MOTOR_BIN2_GPIO GPIO_NUM_12
#define MOTOR_PWMB_GPIO GPIO_NUM_13
#define MOTOR_STBY_GPIO GPIO_NUM_14

// 复用 bread-compact-wifi-lcd 原板的 ST7789 SPI LCD 接线。
#define DISPLAY_BACKLIGHT_PIN GPIO_NUM_42
#define DISPLAY_MOSI_PIN GPIO_NUM_47
#define DISPLAY_CLK_PIN GPIO_NUM_21
#define DISPLAY_DC_PIN GPIO_NUM_40
#define DISPLAY_RST_PIN GPIO_NUM_45
#define DISPLAY_CS_PIN GPIO_NUM_41
#define DISPLAY_WIDTH 240
#define DISPLAY_HEIGHT 320
#define DISPLAY_MIRROR_X false
#define DISPLAY_MIRROR_Y false
#define DISPLAY_SWAP_XY false
#define DISPLAY_INVERT_COLOR true
#define DISPLAY_RGB_ORDER LCD_RGB_ELEMENT_ORDER_RGB
#define DISPLAY_OFFSET_X 0
#define DISPLAY_OFFSET_Y 0
#define DISPLAY_BACKLIGHT_OUTPUT_INVERT false
#define DISPLAY_SPI_MODE 0
#define LCD_TYPE_ST7789_SERIAL
#endif
